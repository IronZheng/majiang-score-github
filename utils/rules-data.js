function card(rank, suit) {
  return {
    rank,
    suit,
    red: suit === '♥' || suit === '♦'
  };
}

function tile(label, tone = 'wan') {
  const text = String(label || '');
  const numberMap = {
    一: 1,
    二: 2,
    三: 3,
    四: 4,
    五: 5,
    六: 6,
    七: 7,
    八: 8,
    九: 9
  };
  const suitMap = {
    万: 'wan',
    筒: 'tong',
    条: 'tiao'
  };
  const namedMap = {
    东: 'east',
    红中: 'red',
    发财: 'fa',
    白板: 'bai',
    财神: 'caishen'
  };

  let tileName = namedMap[text] || '';
  if (!tileName && text.length >= 2) {
    const number = numberMap[text[0]];
    const suit = suitMap[text[text.length - 1]];
    if (number && suit) tileName = `${suit}-${number}`;
  }

  return {
    label,
    tone,
    image: tileName ? `/assets/tiles/${tileName}.svg` : ''
  };
}

